  /* ============================================================
   *  状态
   * ============================================================ */
  function blank() {
    return { chapter: null, step: 0, flags: {}, done: [], items: {}, clues: [] };
  }

  function st() {
    const s = E.state.story;
    if (!s || typeof s !== 'object') { E.state.story = blank(); }
    const v = E.state.story;
    if (typeof v.step !== 'number') v.step = 0;
    if (!v.flags) v.flags = {};
    if (!Array.isArray(v.done)) v.done = [];
    if (!v.items) v.items = {};
    if (!Array.isArray(v.clues)) v.clues = [];
    return v;
  }

  function cur() {
    const s = st();
    return s.chapter && CHAPTERS[s.chapter] ? CHAPTERS[s.chapter] : null;
  }

  function stepDef() {
    const c = cur();
    if (!c) return null;
    return c.steps[st().step] || null;
  }

  function isStep(id) {
    const d = stepDef();
    return !!d && d.id === id;
  }

  /* ---------------- 章节推进 ---------------- */

  function startChapter(id) {
    if (!CHAPTERS[id]) return false;
    const s = st();
    s.chapter = id;
    s.step = 0;
    E.log(`—— ${CHAPTERS[id].title}：${CHAPTERS[id].subtitle} ——`, 'phase');
    E.emit(); E.save();
    return true;
  }

  function setStep(id) {
    const c = cur();
    if (!c) return false;
    const i = c.steps.findIndex(x => x.id === id);
    if (i < 0) return false;
    st().step = i;
    E.emit(); E.save();
    return true;
  }

  function advance() {
    const c = cur();
    if (!c) return false;
    const s = st();
    if (s.step >= c.steps.length - 1) return finish();
    s.step += 1;
    E.emit(); E.save();
    return true;
  }

  function nextOf(id) {
    const i = ORDER.indexOf(id);
    return i >= 0 && i < ORDER.length - 1 ? ORDER[i + 1] : null;
  }

  /* 章节完成：发奖励、记入 done、自动接下一章 */
  function finish() {
    const c = cur();
    if (!c) return false;
    const s = st();
    if (!s.done.includes(c.id)) s.done.push(c.id);
    if (c.reward && c.reward.rep) {
      E.state.reputation = E.clamp(E.state.reputation + c.reward.rep, 0, 100);
    }
    if (c.reward && c.reward.money) {
      E.state.money += c.reward.money;
    }
    E.log(`主线「${c.title}·${c.subtitle}」完成。${c.reward ? c.reward.text : ''}`, 'good');
    const nx = nextOf(c.id);
    s.chapter = nx;
    s.step = 0;
    if (nx) E.log(`—— ${CHAPTERS[nx].title}：${CHAPTERS[nx].subtitle} ——`, 'phase');
    E.emit(); E.save();
    return true;
  }

  /* ---------------- 道具 / 线索 / 标志 ---------------- */

  function giveItem(k, n) {
    const s = st();
    s.items[k] = (s.items[k] || 0) + (n == null ? 1 : n);
    E.emit(); E.save();
  }

  function takeItem(k, n) {
    const s = st();
    const q = n == null ? 1 : n;
    if ((s.items[k] || 0) < q) return false;
    s.items[k] -= q;
    if (s.items[k] <= 0) delete s.items[k];
    E.emit(); E.save();
    return true;
  }

  function itemCount(k) { return st().items[k] || 0; }

  function setFlag(k, v) {
    st().flags[k] = v === undefined ? true : v;
    E.emit(); E.save();
  }

  function flag(k) { return !!st().flags[k]; }

  function addClue(id) {
    const s = st();
    if (!s.clues.includes(id)) {
      s.clues.push(id);
      E.log(`线索：${(CLUES[id] || {}).name || id}`, 'good');
    }
    E.emit(); E.save();
  }

  function hasClue(id) { return st().clues.includes(id); }

  /* ============================================================
   *  供 UI 用的小工具
   * ============================================================ */

  /* 当前进度的一行摘要，给 HUD / 委托页用 */
  function progress() {
    const c = cur();
    if (!c) return { on: false, title: '自由经营', goal: '', hint: '', step: 0, total: 0 };
    const d = stepDef();
    return {
      on: true,
      title: `${c.title} · ${c.subtitle}`,
      goal: d ? d.goal : '',
      hint: d ? d.hint : '',
      step: st().step + 1,
      total: c.steps.length,
      id: c.id,
      stepId: d ? d.id : ''
    };
  }

  /* 章节列表：给委托页画目录 */
  function catalog() {
    const s = st();
    return ORDER.map(id => {
      const c = CHAPTERS[id];
      const done = s.done.includes(id);
      const active = s.chapter === id;
      const locked = !done && !active;
      return {
        id, no: c.no, title: c.title, subtitle: c.subtitle, sugar: c.sugar,
        place: c.place, brief: c.brief, done, active, locked
      };
    });
  }

  return {
    CHAPTERS, ORDER, SCRIPTS, ITEMS, CLUES, SNEAKS,
    blank,
    state: st, chapter: cur, step: stepDef, isStep,
    startChapter, setStep, advance, finish,
    giveItem, takeItem, itemCount, setFlag, flag, addClue, hasClue,
    progress, catalog
  };
